#!/usr/bin/env node
/**
 * Offline fallback for `npx convex codegen`: writes convex/_generated/*
 * (the same standard files Convex generates) without needing a deployment.
 * Use it to type-check and run convex-test before a project exists.
 * `npx convex dev` overwrites these files with the official output.
 *
 *   node scripts/offline-codegen.mjs
 */
import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const convexDir = join(here, "..", "convex");
const out = join(convexDir, "_generated");
const SKIP = new Set(["schema.ts", "auth.config.ts", "convex.config.ts"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return name === "_generated" || name.startsWith(".") ? [] : walk(full);
    if (!/\.(ts|js)$/.test(name) || name.endsWith(".d.ts") || name.includes(".test.")) return [];
    return [full];
  });
}

const modules = walk(convexDir)
  .map((f) => relative(convexDir, f).split(sep).join("/").replace(/\.(ts|js)$/, ""))
  .filter((m) => !SKIP.has(`${m}.ts`))
  .sort();

const ident = (m) => m.replace(/[^A-Za-z0-9]/g, "_");
const header = "/* eslint-disable */\n/**\n * Generated by scripts/offline-codegen.mjs (offline stand-in for `convex codegen`).\n * Run `npx convex dev` to replace with the official output.\n */\n";

mkdirSync(out, { recursive: true });

writeFileSync(
  join(out, "api.d.ts"),
  `${header}
import type { ApiFromModules, FilterApi, FunctionReference } from "convex/server";
${modules.map((m) => `import type * as ${ident(m)} from "../${m}.js";`).join("\n")}

declare const fullApi: ApiFromModules<{
${modules.map((m) => `  ${JSON.stringify(m)}: typeof ${ident(m)};`).join("\n")}
}>;
export declare const api: FilterApi<typeof fullApi, FunctionReference<any, "public">>;
export declare const internal: FilterApi<typeof fullApi, FunctionReference<any, "internal">>;
export declare const components: {};
`,
);

writeFileSync(
  join(out, "api.js"),
  `${header}
import { anyApi, componentsGeneric } from "convex/server";
export const api = anyApi;
export const internal = anyApi;
export const components = componentsGeneric();
`,
);

writeFileSync(
  join(out, "dataModel.d.ts"),
  `${header}
import type { DataModelFromSchemaDefinition, DocumentByName, SystemTableNames, TableNamesInDataModel } from "convex/server";
import type { GenericId } from "convex/values";
import schema from "../schema.js";

export type DataModel = DataModelFromSchemaDefinition<typeof schema>;
export type TableNames = TableNamesInDataModel<DataModel>;
export type Doc<TableName extends TableNames> = DocumentByName<DataModel, TableName>;
export type Id<TableName extends TableNames | SystemTableNames> = GenericId<TableName>;
`,
);

writeFileSync(
  join(out, "server.d.ts"),
  `${header}
import type {
  ActionBuilder,
  GenericActionCtx,
  GenericDatabaseReader,
  GenericDatabaseWriter,
  GenericMutationCtx,
  GenericQueryCtx,
  HttpActionBuilder,
  MutationBuilder,
  QueryBuilder,
} from "convex/server";
import type { DataModel } from "./dataModel.js";

export declare const query: QueryBuilder<DataModel, "public">;
export declare const internalQuery: QueryBuilder<DataModel, "internal">;
export declare const mutation: MutationBuilder<DataModel, "public">;
export declare const internalMutation: MutationBuilder<DataModel, "internal">;
export declare const action: ActionBuilder<DataModel, "public">;
export declare const internalAction: ActionBuilder<DataModel, "internal">;
export declare const httpAction: HttpActionBuilder;
export type QueryCtx = GenericQueryCtx<DataModel>;
export type MutationCtx = GenericMutationCtx<DataModel>;
export type ActionCtx = GenericActionCtx<DataModel>;
export type DatabaseReader = GenericDatabaseReader<DataModel>;
export type DatabaseWriter = GenericDatabaseWriter<DataModel>;
`,
);

writeFileSync(
  join(out, "server.js"),
  `${header}
import {
  actionGeneric,
  httpActionGeneric,
  internalActionGeneric,
  internalMutationGeneric,
  internalQueryGeneric,
  mutationGeneric,
  queryGeneric,
} from "convex/server";
export const query = queryGeneric;
export const internalQuery = internalQueryGeneric;
export const mutation = mutationGeneric;
export const internalMutation = internalMutationGeneric;
export const action = actionGeneric;
export const internalAction = internalActionGeneric;
export const httpAction = httpActionGeneric;
`,
);

console.log(`Wrote convex/_generated for ${modules.length} modules.`);
